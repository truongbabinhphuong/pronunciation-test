#!/usr/bin/env node

/**
 * Build script to generate config.js from .env file
 * This allows the static webapp to use environment variables
 */

const fs = require('fs');
const path = require('path');

// Read .env file
const envPath = path.join(__dirname, '.env');
const envExamplePath = path.join(__dirname, '.env.example');

let envContent = '';

// Try to read .env first, fall back to .env.example
if (fs.existsSync(envPath)) {
    envContent = fs.readFileSync(envPath, 'utf8');
    console.log('✓ Reading configuration from .env');
} else if (fs.existsSync(envExamplePath)) {
    envContent = fs.readFileSync(envExamplePath, 'utf8');
    console.log('⚠ .env not found, using .env.example');
    console.log('  For production, copy .env.example to .env and configure it');
} else {
    console.error('✗ Neither .env nor .env.example found');
    process.exit(1);
}

// Parse .env file
const config = {};
const lines = envContent.split('\n');

lines.forEach(line => {
    // Skip comments and empty lines
    if (line.trim().startsWith('#') || !line.trim()) {
        return;
    }
    
    // Parse KEY=value
    const match = line.match(/^([^=]+)=(.*)$/);
    if (match) {
        const key = match[1].trim();
        const value = match[2].trim();
        config[key] = value;
    }
});

// Generate config.js
const configJs = `/**
 * Configuration loaded from .env file
 * This file is auto-generated by build.js
 * DO NOT EDIT MANUALLY - changes will be overwritten
 */

window.APP_CONFIG = {
    API_URL: '${config.API_URL || 'http://localhost:3000'}',
    API_KEY: '${config.API_KEY || ''}'
};

console.log('Configuration loaded:', {
    API_URL: window.APP_CONFIG.API_URL,
    API_KEY: window.APP_CONFIG.API_KEY ? '***configured***' : '(not set)'
});
`;

// Write config.js
const configPath = path.join(__dirname, 'config.js');
fs.writeFileSync(configPath, configJs);

console.log('✓ Generated config.js successfully');
console.log('  API_URL:', config.API_URL || 'http://localhost:3000');
console.log('  API_KEY:', config.API_KEY ? '***configured***' : '(not set)');
